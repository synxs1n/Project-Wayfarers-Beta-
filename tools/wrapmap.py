# v0.18.5 cleanup step 2: who wraps what. Reads v3/ statically and prints, per function, every raw wrapper
# (`{const f0=fn;fn=function...}` and `fn=function` reassignments) and every HOOK registration, in load order (v3build.py MODS).
# Usage (repo root): python3 tools/wrapmap.py            prints the table (most wrapped first)
#                    python3 tools/wrapmap.py --write    also rewrites docs/wrapmap.md
#                    python3 tools/wrapmap.py NAME       the chain of one function, with the line of each wrapper
# A function that is HOOK.def'd shows "def@module"; raw wraps on top of a def'd function are the ones to convert to registrations.
import os,re,sys
d=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
g={};exec(re.search(r'^MODS=.*$',open(os.path.join(d,'v3build.py')).read(),re.M).group(0),g);MODS=g['MODS']
WRAP=re.compile(r'\{\s*const\s+(\w+)\s*=\s*([A-Za-z_$][\w$]*)\s*;\s*\2\s*=\s*(?:async\s*)?function')
REAS=re.compile(r'(?:^|[;{}\n])\s*([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?function\b')
HOOKR=re.compile(r"HOOK\.(before|after|wrap|xform)\(\s*'([^']+)'\s*,\s*'([^']+)'\s*,\s*'([^']*)'")
DEF=re.compile(r"([A-Za-z_$][\w$]*)\s*=\s*HOOK\.def\(\s*'([^']+)'")
DECL=re.compile(r'^(?:function\s+([A-Za-z_$][\w$]*)|(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:function|\(|[A-Za-z_$][\w$]*\s*=>))',re.M)
chain={};owner={};defd={}
for m in MODS:
    s=open(os.path.join(d,'v3',m),encoding='utf-8').read()
    for mt in DECL.finditer(s):
        n=mt.group(1) or mt.group(2)
        if n and n not in owner:owner[n]=m
    for mt in DEF.finditer(s):defd[mt.group(2)]=m
    seen=set()
    for mt in WRAP.finditer(s):
        n=mt.group(2);ln=s.count('\n',0,mt.start())+1;seen.add(ln)
        chain.setdefault(n,[]).append((m,'raw',ln,''))
    for mt in REAS.finditer(s):
        n=mt.group(1);ln=s.count('\n',0,mt.start(1))+1
        if ln in seen or n not in owner or owner[n]==m:continue
        # a reassignment of another module's function without the f0 idiom (a full replacement)
        chain.setdefault(n,[]).append((m,'replace',ln,''))
    for mt in HOOKR.finditer(s):
        ln=s.count('\n',0,mt.start())+1
        chain.setdefault(mt.group(2),[]).append((m,mt.group(1),ln,mt.group(4)))
rows=sorted(chain.items(),key=lambda kv:(-len(kv[1]),kv[0]))
args=[a for a in sys.argv[1:] if not a.startswith('--')]
if args:
    for n in args:
        print('%s: owner %s%s'%(n,owner.get(n,'?'),', HOOK.def in '+defd[n] if n in defd else ''))
        for m,k,ln,why in chain.get(n,[]):print('  %-18s %-8s %s:%d %s'%(m,k,m,ln,why))
    sys.exit()
raw_total=sum(1 for v in chain.values() for x in v if x[1] in('raw','replace'))
hook_total=sum(1 for v in chain.values() for x in v if x[1] not in('raw','replace'))
lines=['# Wrap map (generated by tools/wrapmap.py)','',
 'Who wraps what, in load order. `raw` is the `{const f0=fn;fn=function...}` idiom, `replace` a reassignment without calling the old body, the rest are HOOK registrations. "def" names the module that HOOK.def\'d the function. Raw wraps on a def\'d function should become registrations; functions with many raw wraps and no def are the candidates for one.','',
 '%d functions wrapped; %d raw wraps or replacements, %d hook registrations.'%(len(chain),raw_total,hook_total),'',
 '| function | owner | def | layers | chain (load order) |','|---|---|---|---|---|']
for n,v in rows:
    lines.append('| %s | %s | %s | %d | %s |'%(n,owner.get(n,'?'),defd.get(n,''),len(v),' → '.join('%s:%s'%(m,k) for m,k,_,_ in v)))
out='\n'.join(lines)+'\n'
if '--write' in sys.argv:
    open(os.path.join(d,'docs','wrapmap.md'),'w',encoding='utf-8').write(out);print('wrote docs/wrapmap.md (%d functions)'%len(chain))
else:print(out)
